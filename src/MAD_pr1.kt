//Store & Display Values in Different Variables:
fun main() {
    var i = 200
    var j: Int = 100
    var k: String = "Naimish"
    var F: Float = 2.8f
    var C: Char = 'N'
    var D: Double = 2.8
    var b: Boolean = false
    var long: Long = 1000000L
    var short: Short = 10
    var byte: Byte = 1
    val Z = 20000

    println("i = " + i)
    println("j = " + j)
    println("k = " + k)
    println("F = " + F)
    println("C = " + C)
    println("D = " + D)
    println("b = " + b)
    println("long = " + long)
    println("short = " + short)
    println("byte = " + byte)
    println("Z = " + Z)
}